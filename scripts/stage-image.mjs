// Stages what the image serves: the built site without the forwarding stubs and the Pages CNAME file, the nginx
// redirect map, and /healthz with the release baked in.
//
//   node scripts/stage-image.mjs [dist] [stage]      (VERSION and REVISION from the environment)
//
// GitHub Pages cannot send a 301, so Astro writes a page that forwards with a meta refresh (the old Gateway release
// notes address is one). nginx answers those addresses with a real 301 and the stub is left out of the image.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, rmdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ORIGIN = 'https://hotloop.io';

const walk = (dir, out = []) => {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    statSync(p).isDirectory() ? walk(p, out) : out.push(p);
  }
  return out;
};

// Every built .html file as { path: '/releases/gateway/index.html', stub: <absolute target or null> }.
export function pagesOf(dist) {
  return walk(dist)
    .filter((f) => f.endsWith('.html'))
    .map((f) => {
      const path = '/' + relative(dist, f).split(sep).join('/');
      const m = readFileSync(f, 'utf8').match(/<meta[^>]+http-equiv=["']refresh["'][^>]*content=["'][^"']*url=([^"'\s]+)["']/i);
      return { path, stub: m ? absolute(m[1]) : null };
    })
    .sort((a, b) => (a.path < b.path ? -1 : 1));
}

export function absolute(target) {
  if (/^https?:\/\//.test(target)) return target;
  return ORIGIN + (target.startsWith('/') ? target : '/' + target);
}

// The URL a built file answers at: directory format, so x/index.html is /x/.
export const urlOf = (path) => (path === '/index.html' ? '/' : path.replace(/index\.html$/, ''));

export function buildMap(pages) {
  const m = new Map();
  for (const { path, stub } of pages) {
    if (!stub) continue;
    const from = urlOf(path);
    m.set(from, stub);
    if (from.endsWith('/') && from !== '/') m.set(from.slice(0, -1), stub);
  }
  return m;
}

export function renderConf(map) {
  const lines = [...map].sort(([a], [b]) => (a < b ? -1 : 1)).map(([f, t]) => `    ${f} ${t};`);
  return [
    '# Generated by scripts/stage-image.mjs. Do not edit; edit the pages.',
    '# $uri is the decoded path with no query string; the server block adds the query back.',
    'map $uri $legacy_redirect {',
    '    default "";',
    ...lines,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dist = process.argv[2] || 'dist';
  const stage = process.argv[3] || 'stage';
  const pages = pagesOf(dist);
  rmSync(stage, { recursive: true, force: true });
  mkdirSync(stage, { recursive: true });
  cpSync(dist, join(stage, 'site'), { recursive: true });
  for (const { path, stub } of pages) {
    if (!stub) continue;
    rmSync(join(stage, 'site', path));
    const dir = dirname(join(stage, 'site', path));
    if (readdirSync(dir).length === 0) rmdirSync(dir);
  }
  rmSync(join(stage, 'site', 'CNAME'), { force: true });
  const map = buildMap(pages);
  writeFileSync(join(stage, 'redirects.conf'), renderConf(map));
  writeFileSync(
    join(stage, 'site', 'healthz'),
    JSON.stringify({ status: 'ok', build: { version: process.env.VERSION || 'dev', revision: process.env.REVISION || 'unknown' } }),
  );
  console.log(`stage: ${pages.filter((p) => p.stub).length} stubs left out, ${map.size} redirects -> ${stage}/`);
}
